import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build as bundleJavaScript } from "esbuild";

export const docsDir = fileURLToPath(new URL("../", import.meta.url));
const sourceDir = path.join(docsDir, "src");
export async function synthesize() {
  const bundle = await bundleJavaScript({
    absWorkingDir: docsDir,
    entryPoints: ["src/app.js"],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: "es2022",
    charset: "utf8",
    legalComments: "none",
    logLevel: "silent"
  });
  const javascript = bundle.outputFiles[0].text;
  let html = await readFile(path.join(sourceDir, "index.html"), "utf8");
  const links = [...html.matchAll(/<link rel="stylesheet" href="(\.\/styles\/[^"\n]+\.css)">/g)];
  for (const [tag, href] of links) {
    const css = await readFile(path.join(sourceDir, href), "utf8");
    html = html.replace(tag, () => `<style>\n${css.replace(/<\/style/gi, "<\\/style")}  </style>`);
  }
  html = html.replace('<script type="module" src="./app.js"></script>', () => `<script>\n${javascript.replace(/<\/script/gi, "<\\/script")}\n  </script>`);
  html = html.replace("script-src 'self' 'unsafe-inline'", "script-src 'unsafe-inline'")
    .replace("style-src 'self' 'unsafe-inline'", "style-src 'unsafe-inline'");
  return html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by node docs/scripts/build.mjs. Edit docs/src instead. -->");
}

export async function build({ check = false } = {}) {
  const output = path.join(docsDir, "index.html");
  const html = await synthesize();
  if (check) {
    const existing = await readFile(output, "utf8").catch(error => {
      if (error.code === "ENOENT") return null;
      throw error;
    });
    if (existing !== html) throw new Error("docs/index.html is stale. Run node docs/scripts/build.mjs.");
  } else {
    await writeFile(output, html);
  }
  return output;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const output = await build({ check: process.argv.includes("--check") });
    console.log(`${process.argv.includes("--check") ? "Verified" : "Built"} ${output}`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
