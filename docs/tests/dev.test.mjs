import assert from "node:assert/strict";
import { once } from "node:events";
import { test } from "node:test";
import { createDevServer } from "../scripts/dev.mjs";

test("the preview serves source modules and the built document with correct content types", async t => {
  const server = createDevServer();
  t.after(() => { server.closeAllConnections(); server.close(); });
  server.listen(0, "127.0.0.1");
  await once(server, "listening");
  const base = `http://127.0.0.1:${server.address().port}`;
  for (const [pathname, contentType, expected] of [
    ["/", "text/html", '<script type="module"'],
    ["/src/app.js", "text/javascript", "loadStored();"],
    ["/src/styles/studio.css", "text/css", ":root"],
    ["/index.html", "text/html", "Generated by node"]
  ]) {
    const response = await fetch(base + pathname);
    assert.equal(response.status, 200);
    assert.ok(response.headers.get("content-type").startsWith(contentType));
    assert.ok((await response.text()).includes(expected));
  }
  assert.equal((await fetch(base + "/missing.js")).status, 404);
  assert.equal((await fetch(base + "/%2e%2e%2fREADME.md")).status, 403);
});
